// TestRunRejectsNestedClientDefault verifies that x-client-default is only
// allowed on top-level properties, matching the runtime fill scope.
func TestRunRejectsNestedClientDefault(t *testing.T) {
	source := strings.Replace(instanceScopedToolSource, `        topicName:
          type: string
          minLength: 1
`, `        filter:
          type: object
          properties:
            timestamp:
              type: integer
              x-client-default: NOW
`, 1)
	input, output := writeCatalogSource(t, source)
	err := run([]string{"-input", input, "-output", output})
	if err == nil || !strings.Contains(err.Error(), "only supported on top-level properties") {
		t.Fatalf("err = %v, want nested x-client-default failure", err)
	}
}

// TestRunRejectsReservedInstanceIDFlag verifies that per-tool properties
// cannot claim the global --instance-id flag, neither via x-cli-flag nor via
// a nested property literally named instanceId.
func TestRunRejectsReservedInstanceIDFlag(t *testing.T) {
	source := strings.Replace(instanceScopedToolSource, `        topicName:
          type: string
          minLength: 1
`, `        topicName:
          type: string
          minLength: 1
          x-cli-flag: instance-id
`, 1)
	input, output := writeCatalogSource(t, source)
	err := run([]string{"-input", input, "-output", output})
	if err == nil || !strings.Contains(err.Error(), "reserved CLI flag --instance-id") {
		t.Fatalf("err = %v, want reserved flag failure", err)
	}

	nested := strings.Replace(instanceScopedToolSource, `        topicName:
          type: string
          minLength: 1
`, `        filter:
          type: object
          properties:
            instanceId:
              type: string
`, 1)
	input, output = writeCatalogSource(t, nested)
	err = run([]string{"-input", input, "-output", output})
	if err == nil || !strings.Contains(err.Error(), "reserved CLI flag --instance-id") {
		t.Fatalf("err = %v, want nested instanceId rejection", err)
	}
}
