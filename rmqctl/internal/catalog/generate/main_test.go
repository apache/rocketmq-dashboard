const instanceScopedToolSource = `version: 1.0.0
minimumClientVersion: 1.0.0
tools:
  - name: rmq.topic.list
    cli:
      resource: topic
      verb: list
    description: List topics.
    riskLevel: L1
    permission: topic:read
    requiredCapabilities: []
    inputSchema:
      type: object
      required:
        - instanceId
      properties:
        instanceId:
          type: string
          minLength: 1
        topicName:
          type: string
          minLength: 1
    outputSchema:
      type: object
      properties:
        items:
          type: array
          items:
            type: object
    viewHint: table
`

const platformToolSource = `version: 1.0.0
minimumClientVersion: 1.0.0
tools:
  - name: rmq.cluster.list
    cli:
      resource: cluster
      verb: list
    description: List clusters.
    riskLevel: L1
    permission: cluster:read
    requiredCapabilities: []
    inputSchema:
      type: object
      properties:
        status:
          type: string
          minLength: 1
    outputSchema:
      type: object
      properties:
        items:
          type: array
          items:
            type: object
    viewHint: table
`

func writeCatalogSource(t *testing.T, source string) (input string, output string) {
	t.Helper()
	directory := t.TempDir()
	input = filepath.Join(directory, "rmq-tools.yaml")
	output = filepath.Join(directory, "catalog_gen.go")
	if err := os.WriteFile(input, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	return input, output
}

func TestRunGeneratesAndVerifiesCatalog(t *testing.T) {
	input, output := writeCatalogSource(t, instanceScopedToolSource)

	arguments := []string{"-input", input, "-output", output}
	if err := run(arguments); err != nil {
		t.Fatalf("generate catalog: %v", err)
	}
	generated, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	text := string(generated)
	for _, expected := range []string{
		"Code generated by cataloggen. DO NOT EDIT.",
		`Name:                 "rmq.topic.list"`,
		`Permission:           "topic:read"`,
		`RequiredCapabilities: []string{}`,
		`{Name: "instanceId", Flag: "instance-id", Kind: StringField, Required: true, MinLength: 1}`,
		`{Name: "topicName", Flag: "topic-name", Kind: StringField, MinLength: 1}`,
		`TableDataKey: "items"`,
	} {
		if !strings.Contains(text, expected) {
			t.Fatalf("generated catalog does not contain %q\n%s", expected, text)
		}
	}

	if err := run(append(arguments, "-check")); err != nil {
		t.Fatalf("verify generated catalog: %v", err)
	}
}

// TestRunAcceptsPlatformToolWithoutInstanceID verifies the platform-level
// exemption list (decisions 25/26): exempt tools must not declare instanceId.
func TestRunAcceptsPlatformToolWithoutInstanceID(t *testing.T) {
	input, output := writeCatalogSource(t, platformToolSource)
	if err := run([]string{"-input", input, "-output", output}); err != nil {
		t.Fatalf("generate catalog: %v", err)
	}
	generated, err := os.ReadFile(output)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(generated), "instanceId") {
		t.Fatalf("platform tool catalog must not carry instanceId:\n%s", generated)
	}
}

// TestRunRejectsInstanceScopedToolWithoutInstanceID verifies that non-platform
// tools must declare and require instanceId (decision 7).
func TestRunRejectsInstanceScopedToolWithoutInstanceID(t *testing.T) {
	source := strings.Replace(instanceScopedToolSource, `      required:
        - instanceId
      properties:
        instanceId:
          type: string
          minLength: 1
`, `      properties:
`, 1)
	input, output := writeCatalogSource(t, source)
	err := run([]string{"-input", input, "-output", output})
	if err == nil || !strings.Contains(err.Error(), "must declare instanceId") {
		t.Fatalf("err = %v, want instanceId declaration failure", err)
	}
}

// TestRunRejectsPlatformToolDeclaringInstanceID verifies the exemption is
