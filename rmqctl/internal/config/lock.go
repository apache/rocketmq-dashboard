package config

import (
	"context"
	"os"
	"time"
)

// Closing the descriptor releases the native lock, including on process exit.
// The persistent sidecar is never unlinked, so waiting writers share one inode.
func acquireConfigLock(ctx context.Context, path string) (*os.File, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	file, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	for {
		if err := ctx.Err(); err != nil {
			file.Close()
			return nil, err
		}
		locked, err := tryConfigLock(file)
		if err != nil {
			file.Close()
			return nil, err
		}
		if locked {
			return file, nil
		}
		timer := time.NewTimer(configLockRetry)
		select {
		case <-ctx.Done():
			timer.Stop()
			file.Close()
			return nil, ctx.Err()
		case <-timer.C:
		}
	}
}
